#!/usr/bin/env python3
# Generates src/doom/tables.nuc from Chocolate Doom's tables.c and m_random.c. The original
# tables match no closed-form sin/tan/atan (tested in M1), so they are embedded.
# Usage: scripts/gen-tables.py [path/to/tables.c]
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
choc = os.environ.get("CHOCOLATE_DOOM", "/home/zak/code/chocolate-doom")
src = open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(choc, "src/tables.c")).read()


def table(name):
    m = re.search(name + r"\[[^\]]*\](?:\[[^\]]*\])?\s*=\s*\{(.*?)\};", src, re.S)
    return [int(x, 0) for x in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", m.group(1))]


def emit(out, name, elt, values, per_line):
    out.append("(defconst %s (array %s" % (name, elt))
    for i in range(0, len(values), per_line):
        out.append("  " + " ".join(str(v) for v in values[i:i + per_line]))
    out[-1] += "))"
    out.append("")


out = [
    "; Copyright(C) 1993-1996 Id Software, Inc.; Copyright(C) 2005-2014 Simon Howard.",
    "; GPLv2 or later; see COPYING.",
    "; Generated by scripts/gen-tables.py from tables.c. Do not edit.",
    "",
    "(ns doom.tables)",
    "",
]
emit(out, "fine-tangent-table", "i32", table("finetangent"), 8)
emit(out, "fine-sine-table", "i32", table("finesine"), 8)
emit(out, "tan-to-angle-table", "ui32", table("tantoangle"), 8)
emit(out, "gamma-table", "ui8", table("gammatable"), 16)
src = open(os.path.join(choc, "src/doom/m_random.c")).read()
emit(out, "rnd-table", "ui8", table("rndtable"), 16)

with open(os.path.join(root, "src/doom/tables.nuc"), "w") as f:
    f.write("\n".join(out))
